import { useEffect, useRef, useState } from 'react';
import { Send } from 'lucide-react';
import { errorMessage, sendChat } from '../lib/api.js';
import { PageTitle, Spinner } from './common.jsx';

const SUGGESTIONS = [
  'Is it safe for my kids to play outside today?',
  'How do I make my bedroom air cleaner cheaply?',
  'Best time for a morning walk?',
];

/** Only genuine Gemini replies are sent back as context; fallback/error bubbles are not. */
export const toHistory = (messages) =>
  messages
    .filter((m) => m.role === 'user' || m.source === 'gemini')
    .map((m) => ({ role: m.role === 'user' ? 'user' : 'model', text: m.text }));

function Message({ m }) {
  const mine = m.role === 'user';
  return (
    <div
      className={`whitespace-pre-wrap rounded-xl p-3 text-sm ${mine ? 'ml-8 bg-teal-400/20' : 'mr-8 bg-navy-900'}`}
    >
      <span className="sr-only">{mine ? 'You said: ' : 'AeroSage AI said: '}</span>
      {m.text}
      {m.source === 'gemini' && (
        <div className="mt-1 text-xs text-slate-300">AI-generated by Gemini</div>
      )}
      {m.source === 'fallback' && (
        <div className="mt-2 rounded bg-amber-400/20 p-2 text-xs text-amber-200">
          <b>Basic guidance, not AI-generated.</b> {m.note}
        </div>
      )}
    </div>
  );
}

export default function Chat({ ctx, fam, messages, setMessages }) {
  const [q, setQ] = useState('');
  const [busy, setBusy] = useState(false);
  const endRef = useRef(null);

  useEffect(() => {
    endRef.current?.scrollIntoView?.({ block: 'nearest' });
  }, [messages, busy]);

  const send = async (text) => {
    const message = (text ?? q).trim();
    if (!message || busy) return;
    setQ('');
    const history = toHistory(messages);
    setMessages((prev) => [...prev, { role: 'user', text: message }]);
    setBusy(true);
    try {
      const r = await sendChat({ message, history, context: ctx, profile: fam });
      setMessages((prev) => [
        ...prev,
        {
          role: 'ai',
          text: r.text,
          source: r.source ?? (r.ai ? 'gemini' : 'fallback'),
          note: r.note,
        },
      ]);
    } catch (e) {
      setMessages((prev) => [...prev, { role: 'ai', text: errorMessage(e), source: 'error' }]);
    } finally {
      setBusy(false);
    }
  };

  return (
    <section className="card">
      <PageTitle>AeroSage AI Assistant</PageTitle>
      <p className="text-xs text-slate-300">
        Answers are AI-generated suggestions based on the readings shown; not medical advice.
        {ctx.demo && ' The current readings are synthetic demo data.'}
      </p>
      <div className="my-3 flex flex-wrap gap-2">
        {SUGGESTIONS.map((s) => (
          <button
            key={s}
            type="button"
            disabled={busy}
            onClick={() => send(s)}
            className="rounded-full border border-white/30 px-3 py-1.5 text-xs hover:bg-white/5 disabled:opacity-50"
          >
            {s}
          </button>
        ))}
      </div>
      <div
        role="log"
        aria-label="Conversation with AeroSage AI"
        aria-live="polite"
        aria-relevant="additions"
        className="max-h-[50vh] space-y-2 overflow-y-auto"
        // A scrollable region must be keyboard-focusable so it can be scrolled without a mouse.
        // eslint-disable-next-line jsx-a11y/no-noninteractive-tabindex
        tabIndex={0}
      >
        <div className="mr-8 rounded-xl bg-navy-900 p-3 text-sm">
          Hi! I&apos;m AeroSage AI. Ask me anything about air quality in {ctx.place}.
        </div>
        {messages.map((m, i) => (
          <Message key={i} m={m} />
        ))}
        {busy && (
          <p className="text-sm text-slate-300">
            <Spinner label="AeroSage AI is thinking…" />
          </p>
        )}
        <div ref={endRef} />
      </div>
      <form
        onSubmit={(e) => {
          e.preventDefault();
          send();
        }}
        className="mt-3 flex gap-2"
      >
        <label htmlFor="chat-input" className="sr-only">
          Your question
        </label>
        <input
          id="chat-input"
          className="inp"
          maxLength={2000}
          autoComplete="off"
          value={q}
          onChange={(e) => setQ(e.target.value)}
          placeholder="Ask about your family, routine, home…"
        />
        <button className="btn" aria-label="Send message" disabled={busy || !q.trim()}>
          <Send aria-hidden="true" size={16} />
        </button>
      </form>
    </section>
  );
}
