import { useEffect, useRef, useState } from 'react';
import { Send } from 'lucide-react';
import { MAX_MESSAGE_LENGTH } from '../constants.js';
import { PageTitle, Spinner } from './common.jsx';

const SUGGESTIONS = [
  'Is it safe for my kids to play outside today?',
  'How do I make my bedroom air cleaner cheaply?',
  'Best time for a morning walk?',
];

/** One chat bubble. Replies state where they came from: Gemini, or rule-based fallback guidance. */
function Message({ message }) {
  const fromUser = message.role === 'user';
  return (
    <div
      className={`whitespace-pre-wrap rounded-xl p-3 text-sm ${fromUser ? 'ml-8 bg-teal-400/20' : 'mr-8 bg-navy-900'}`}
    >
      <span className="sr-only">{fromUser ? 'You said: ' : 'AeroSage AI said: '}</span>
      {message.text}
      {message.source === 'gemini' && (
        <div className="mt-1 text-xs text-slate-300">AI-generated by Gemini</div>
      )}
      {message.source === 'fallback' && (
        <div className="mt-2 rounded bg-amber-400/20 p-2 text-xs text-amber-200">
          <b>Basic guidance, not AI-generated.</b> {message.note}
        </div>
      )}
    </div>
  );
}

/** Presentational chat page; the conversation itself is owned by `useAssistantChat`. */
export default function Chat({ context, chat }) {
  const { messages, busy, send } = chat;
  const [draft, setDraft] = useState('');
  const end = useRef(null);

  useEffect(() => {
    end.current?.scrollIntoView?.({ block: 'nearest' });
  }, [messages, busy]);

  const submit = (text) => {
    if (!text.trim() || busy) {
      return;
    }
    setDraft('');
    send(text);
  };

  return (
    <section className="card">
      <PageTitle>AeroSage AI Assistant</PageTitle>
      <p className="text-xs text-slate-300">
        Answers are AI-generated suggestions based on the readings shown (estimates from model
        data); not medical advice.
        {context.demo && ' The current readings are synthetic demo data.'}
        {context.stale && ' The current reading may be out of date.'}
      </p>
      <div className="my-3 flex flex-wrap gap-2">
        {SUGGESTIONS.map((suggestion) => (
          <button
            key={suggestion}
            type="button"
            disabled={busy}
            onClick={() => submit(suggestion)}
            className="rounded-full border border-white/30 px-3 py-1.5 text-xs hover:bg-white/5 disabled:opacity-50"
          >
            {suggestion}
          </button>
        ))}
      </div>
      <div
        role="log"
        aria-label="Conversation with AeroSage AI"
        aria-live="polite"
        aria-relevant="additions"
        className="max-h-[50vh] space-y-2 overflow-y-auto"
        // A scrollable region must be keyboard-focusable so it can be scrolled without a mouse.
        // eslint-disable-next-line jsx-a11y/no-noninteractive-tabindex
        tabIndex={0}
      >
        <div className="mr-8 rounded-xl bg-navy-900 p-3 text-sm">
          Hi! I&apos;m AeroSage AI. Ask me anything about air quality in {context.place}.
        </div>
        {messages.map((message, index) => (
          <Message key={index} message={message} />
        ))}
        {busy && (
          <p className="text-sm text-slate-300">
            <Spinner label="AeroSage AI is thinking…" />
          </p>
        )}
        <div ref={end} />
      </div>
      <form
        onSubmit={(event) => {
          event.preventDefault();
          submit(draft);
        }}
        className="mt-3 flex gap-2"
      >
        <label htmlFor="chat-input" className="sr-only">
          Your question
        </label>
        <input
          id="chat-input"
          className="inp"
          maxLength={MAX_MESSAGE_LENGTH}
          autoComplete="off"
          value={draft}
          onChange={(event) => setDraft(event.target.value)}
          placeholder="Ask about your family, routine, home…"
        />
        <button className="btn" aria-label="Send message" disabled={busy || !draft.trim()}>
          <Send aria-hidden="true" size={16} />
        </button>
      </form>
    </section>
  );
}
